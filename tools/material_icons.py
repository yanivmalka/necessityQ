#!/usr/bin/env python3
"""
Generates app/src/main/kotlin/app/necessityq/ui/icons/Icons.kt: only the Material icons the app uses.

The app used to depend on androidx.compose.material:material-icons-extended, which holds thousands of icons in
every style. R8 had to process all of them in every release build, and that took about three minutes of the
APK build. Instead, this script finds the icons the code uses (Icons.Default.X and Icons.AutoMirrored.Filled.X)
and writes just those, with the same names, into the app's own `Icons` object. The code keeps writing
`Icons.Default.Mic` and only imports app.necessityq.ui.icons.Icons.

The shapes come from the official Material Icons SVGs (Apache 2.0), the same source the Compose icons are made
from. "Default" is the filled style; AutoMirrored icons flip in right-to-left layouts, as in Compose.

To use a new icon: write it in the code as Icons.Default.Name (or Icons.AutoMirrored.Filled.Name), then run from
the repository root:

    mkdir -p /tmp/mdi && (cd /tmp/mdi && npm pack @material-design-icons/svg && tar xzf material-design-icons-svg-*.tgz)
    python3 tools/material_icons.py /tmp/mdi/package/filled

The icon names are the Compose names (QrCodeScanner); the SVG files use snake_case (qr_code_scanner.svg).
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "app/src/main/kotlin"
KOTLIN = SOURCES / "app/necessityq/ui/icons/Icons.kt"
SVG_NS = "{http://www.w3.org/2000/svg}"

USE = re.compile(r"\bIcons\.(Default|AutoMirrored\.Filled)\.([A-Z][A-Za-z0-9]*)")


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Za-z])(?=[0-9])", "_", s)
    return s.lower()


def paths_of(svg: pathlib.Path) -> list[tuple[str, bool]]:
    """The path data of an icon, each with whether it is filled even-odd. Anything else in the SVG is an error."""
    root = ET.parse(svg).getroot()
    if root.get("viewBox") != "0 0 24 24":
        sys.exit(f"{svg.name}: viewBox is {root.get('viewBox')}, expected 0 0 24 24")
    paths = []
    for el in root.iter():
        if el is root:
            continue
        if el.tag == SVG_NS + "circle":
            if set(el.attrib) != {"cx", "cy", "r"}:
                sys.exit(f"{svg.name}: unsupported circle attributes {sorted(el.attrib)}")
            cx, cy, r = (float(el.get(a)) for a in ("cx", "cy", "r"))
            # a circle as two half-circle arcs, starting at its left edge
            paths.append((f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0z", False))
            continue
        if el.tag != SVG_NS + "path":
            sys.exit(f"{svg.name}: unsupported element <{el.tag.removeprefix(SVG_NS)}>")
        extra = set(el.attrib) - {"d", "fill-rule", "clip-rule"}
        if extra:
            sys.exit(f"{svg.name}: unsupported path attributes {sorted(extra)}")
        d = el.get("d", "")
        if not d or '"' in d or "$" in d or "\\" in d:
            sys.exit(f"{svg.name}: unexpected path data")
        paths.append((d, el.get("fill-rule") == "evenodd"))
    if not paths:
        sys.exit(f"{svg.name}: no paths")
    return paths


def property_line(style: str, name: str, svg_dir: pathlib.Path, indent: str) -> str:
    svg = svg_dir / f"{snake(name)}.svg"
    if not svg.exists():
        sys.exit(f"Icons.{style}.{name}: {svg} not found")
    args = [f'"{"AutoMirrored.Filled" if style != "Default" else "Filled"}.{name}"']
    for d, even_odd in paths_of(svg):
        args.append(f'{"evenOdd" if even_odd else "path"}("{d}")')
    mirror = ", autoMirror = true" if style != "Default" else ""
    return f"{indent}val {name}: ImageVector by lazy {{ icon({', '.join(args)}{mirror}) }}"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    svg_dir = pathlib.Path(sys.argv[1])
    used: dict[str, set[str]] = {"Default": set(), "AutoMirrored.Filled": set()}
    for kt in SOURCES.rglob("*.kt"):
        if kt == KOTLIN:
            continue
        for style, name in USE.findall(kt.read_text(encoding="utf-8")):
            used[style].add(name)

    out = [
        "// Generated by tools/material_icons.py from the Material Icons SVGs (Apache License 2.0). Do not edit:",
        "// use a new icon in the code and run the script again (see its header).",
        "package app.necessityq.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.PathFillType",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** The Material icons the app uses, under their Compose names (Icons.Default.Mic). Each is built on first use. */",
        "object Icons {",
        "    object Default {",
    ]
    out += [property_line("Default", n, svg_dir, " " * 8) for n in sorted(used["Default"])]
    out += [
        "    }",
        "",
        "    object AutoMirrored {",
        "        /** Icons that flip in right-to-left layouts (arrows, send, reply). */",
        "        object Filled {",
    ]
    out += [property_line("AutoMirrored.Filled", n, svg_dir, " " * 12) for n in sorted(used["AutoMirrored.Filled"])]
    out += [
        "        }",
        "    }",
        "}",
        "",
        "private class IconPath(val data: String, val fillType: PathFillType)",
        "",
        "private fun path(data: String) = IconPath(data, PathFillType.NonZero)",
        "",
        "private fun evenOdd(data: String) = IconPath(data, PathFillType.EvenOdd)",
        "",
        "/** A 24dp icon on a 24x24 grid, filled black like the Compose Material icons (Icon() tints it). */",
        "private fun icon(name: String, vararg paths: IconPath, autoMirror: Boolean = false): ImageVector =",
        "    ImageVector.Builder(",
        "        name = name,",
        "        defaultWidth = 24.dp,",
        "        defaultHeight = 24.dp,",
        "        viewportWidth = 24f,",
        "        viewportHeight = 24f,",
        "        autoMirror = autoMirror,",
        "    ).apply {",
        "        for (p in paths) addPath(pathData = addPathNodes(p.data), pathFillType = p.fillType, fill = SolidColor(Color.Black))",
        "    }.build()",
        "",
    ]
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text("\n".join(out), encoding="utf-8")
    total = sum(len(v) for v in used.values())
    print(f"{KOTLIN.relative_to(ROOT)}: {total} icons")


if __name__ == "__main__":
    main()
