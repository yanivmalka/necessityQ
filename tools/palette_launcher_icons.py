#!/usr/bin/env python3
"""
Generates the launcher icons of every colour palette ("מראה" ← "ערכת צבעים").

The launcher can only show icons that are resources declared in the manifest, so each pair of icon shape (AppIcon)
and palette (AppPalette) has its own adaptive icon and its own <activity-alias>. The green "Market" icons are the
hand-made originals; every other palette is made from them by recolouring their green:

  - the radial background (light, middle and deep green) becomes the palette's main colour, lit and shaded the
    same way;
  - the green ink on the list (ticks and lines) and the deep-green shadow under the badge follow it.

Cream, white and the amber "running out" badge stay the same in every palette, as in the app.

Run from the repository root after changing a palette's main colour (Theme.kt) or one of the green icons:

    python3 tools/palette_launcher_icons.py

It rewrites the generated drawables and mipmaps, the aliases between the markers in AndroidManifest.xml, and
app/src/main/kotlin/app/necessityq/ui/LauncherIconRes.kt.
"""
import colorsys
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"
KOTLIN = ROOT / "app/src/main/kotlin/app/necessityq/ui/LauncherIconRes.kt"

# Market: the original icon colours (light, middle, deep). Other palettes derive theirs from their main colour.
MARKET = ("4CAF50", "2E7D32", "14451A")

# AppPalette name -> main colour (AppPalette.primary in Theme.kt)
PALETTES = {
    "SEA": "1E5AA8",
    "GRAPE": "5B3A9E",
    "CITRUS": "C2410C",
    "OLIVE": "5F6B2E",
    "GRAPHITE": "37474F",
}

# AppIcon name -> (shape key, manifest alias of the Market icon, mipmap of the Market icon)
ICONS = {
    "DEFAULT": ("list_badge_cycle", ".IconDefault", "ic_launcher"),
    "LIST_BADGE": ("list_badge", ".IconListBadge", "ic_launcher_list_badge"),
    "CART_CYCLE": ("cart_cycle", ".IconCartCycle", "ic_launcher_cart_cycle"),
    "CART_LIST": ("cart_list", ".IconCartList", "ic_launcher_cart_list"),
    "BASKET": ("basket", ".IconBasket", "ic_launcher_basket"),
}

BEGIN = "<!-- palette icons: generated by tools/palette_launcher_icons.py -->"
END = "<!-- end of palette icons -->"


def hls(hex_rgb):
    r, g, b = (int(hex_rgb[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)


def rgb(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, max(0.0, min(1.0, l)), max(0.0, min(1.0, s)))
    return "".join(f"{round(c * 255):02X}" for c in (r, g, b))


def shades(primary):
    """Light, middle and deep, related to each other as the Market greens are."""
    h, l, s = hls(primary)
    (_, ll, ls), (_, ml, ms), (_, dl, ds) = (hls(c) for c in MARKET)
    return (
        rgb(h, l + (ll - ml), s * ls / ms),
        primary,
        rgb(h, l * dl / ml, s * ds / ms),
    )


def recolour(text, colours):
    """Swaps the Market greens for [colours], keeping each one's alpha."""
    for old, new in zip(MARKET, colours):
        text = re.sub(old, new, text, flags=re.IGNORECASE)
    return text


def suffix(palette):
    return palette.lower()


def alias(icon, palette):
    return ICONS[icon][1] + palette.capitalize()


def main():
    background = (RES / "drawable/ic_launcher_background.xml").read_text()
    aliases = []
    kotlin_fg = {}
    for palette, primary in PALETTES.items():
        colours = shades(primary)
        key = suffix(palette)
        (RES / f"drawable/ic_launcher_background_{key}.xml").write_text(
            recolour(background, colours).replace("Deep green radial background", f"{palette.capitalize()} radial background")
        )
        for icon, (shape, _, _) in ICONS.items():
            fg = (RES / f"drawable/ic_launcher_{shape}_foreground.xml").read_text()
            (RES / f"drawable/ic_launcher_{shape}_foreground_{key}.xml").write_text(recolour(fg, colours))
            (RES / f"mipmap-anydpi-v26/ic_launcher_{shape}_{key}.xml").write_text(
                '<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="@drawable/ic_launcher_background_{key}" />\n'
                f'    <foreground android:drawable="@drawable/ic_launcher_{shape}_foreground_{key}" />\n'
                f'    <monochrome android:drawable="@drawable/ic_launcher_{shape}_monochrome" />\n'
                '</adaptive-icon>\n'
            )
            aliases.append(
                "        <activity-alias\n"
                f'            android:name="{alias(icon, palette)}"\n'
                '            android:enabled="false"\n'
                '            android:exported="true"\n'
                f'            android:icon="@mipmap/ic_launcher_{shape}_{key}"\n'
                f'            android:roundIcon="@mipmap/ic_launcher_{shape}_{key}"\n'
                '            android:targetActivity=".ui.MainActivity">\n'
                "            <intent-filter>\n"
                '                <action android:name="android.intent.action.MAIN" />\n'
                '                <category android:name="android.intent.category.LAUNCHER" />\n'
                "            </intent-filter>\n"
                "        </activity-alias>\n"
            )

    manifest = MANIFEST.read_text()
    block = f"        {BEGIN}\n" + "".join(aliases) + f"        {END}\n"
    if BEGIN in manifest:
        manifest = re.sub(r" *" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _: block, manifest, flags=re.S)
    else:
        anchor = "\n        <!-- צ'אט פוד: pushes"
        manifest = manifest.replace(anchor, "\n" + block + anchor, 1)
    MANIFEST.write_text(manifest)

    def when_palette(make):
        lines = ["AppPalette.MARKET -> " + make("MARKET")]
        lines += [f"AppPalette.{p} -> " + make(p) for p in PALETTES]
        return lines

    fg_cases = []
    for icon, (shape, _, _) in ICONS.items():
        inner = when_palette(lambda p, s=shape: f"R.drawable.ic_launcher_{s}_foreground" + ("" if p == "MARKET" else f"_{suffix(p)}"))
        fg_cases.append(f"    AppIcon.{icon} -> when (palette) {{\n" + "".join(f"        {l}\n" for l in inner) + "    }\n")
    bg_cases = when_palette(lambda p: "R.drawable.ic_launcher_background" + ("" if p == "MARKET" else f"_{suffix(p)}"))
    KOTLIN.write_text(
        "// Generated by tools/palette_launcher_icons.py — do not edit by hand.\n"
        "package app.necessityq.ui\n\n"
        "import androidx.annotation.DrawableRes\n"
        "import app.necessityq.R\n"
        "import app.necessityq.platform.AppIcon\n\n"
        "/** The launcher icon's background in [palette]: the palette's main colour, lit from the top-left. */\n"
        "@DrawableRes\n"
        "fun launcherBackground(palette: AppPalette): Int = when (palette) {\n"
        + "".join(f"    {l}\n" for l in bg_cases)
        + "}\n\n"
        "/** The foreground layer of [icon] in [palette] (its ink follows the palette's main colour). */\n"
        "@DrawableRes\n"
        "fun launcherForeground(icon: AppIcon, palette: AppPalette): Int = when (icon) {\n"
        + "".join(fg_cases)
        + "}\n"
    )
    for palette, primary in PALETTES.items():
        print(palette, shades(primary))


if __name__ == "__main__":
    main()
